-- Bootstraps lazy.nvim (https://github.com/folke/lazy.nvim) and loads every
-- spec under lua/plugins/. Add new plugins by dropping a file there —
-- nothing needs to be wired up here.
local lazypath = vim.fn.stdpath("data") .. "/lazy/lazy.nvim"
if not vim.loop.fs_stat(lazypath) then
  vim.fn.system({
    "git",
    "clone",
    "--filter=blob:none",
    "https://github.com/folke/lazy.nvim.git",
    "--branch=stable",
    lazypath,
  })
end
vim.opt.rtp:prepend(lazypath)

require("lazy").setup("plugins")
